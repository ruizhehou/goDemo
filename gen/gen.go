//go:build ignore

// gen.go is a code generator invoked by `go generate`.
// It reads a list of operations and generates a Go source file.
package main

import (
	"os"
	"text/template"
)

// Operation describes a math operation to generate.
type Operation struct {
	Name     string
	Symbol   string
	FuncName string
}

var operations = []Operation{
	{"Add", "+", "Add"},
	{"Subtract", "-", "Subtract"},
	{"Multiply", "*", "Multiply"},
}

var tmpl = template.Must(template.New("ops").Parse(`// Code generated by go generate; DO NOT EDIT.
// Source: gen/gen.go

package mathops

// MathOp performs a math operation on two integers.
type MathOp func(a, b int) int
{{ range . }}
// {{ .Name }} returns a + b using the '{{ .Symbol }}' operator.
func {{ .FuncName }}(a, b int) int {
	return a {{ .Symbol }} b
}
{{ end }}
// All returns a map of all available operations.
func All() map[string]MathOp {
	return map[string]MathOp{
		{{ range . }}"{{ .Name }}": {{ .FuncName }},
		{{ end }}
	}
}
`))

func main() {
	f, err := os.Create("ops_gen.go")
	if err != nil {
		panic(err)
	}
	defer f.Close()

	if err := tmpl.Execute(f, operations); err != nil {
		panic(err)
	}
}
